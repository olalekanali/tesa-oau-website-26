import {Router} from 'express';
import bcrypt from 'bcryptjs';
import jwt from 'jsonwebtoken';
import {body,validationResult} from 'express-validator';
import User from '../models/User.js';
import {requireAuth} from '../middleware/auth.js';
const router=Router();
router.post('/sign-in',[body('email').isEmail().normalizeEmail(),body('password').isLength({min:1})],async(req,res,next)=>{try{const errors=validationResult(req);if(!errors.isEmpty())return res.status(400).json({message:'Enter a valid email and password.'});const user=await User.findOne({email:req.body.email});if(!user||!await bcrypt.compare(req.body.password,user.passwordHash))return res.status(401).json({message:'Email or password is incorrect.'});const token=jwt.sign({id:user._id,name:user.name,email:user.email,role:user.role},process.env.JWT_SECRET,{expiresIn:process.env.JWT_EXPIRES_IN||'8h'});res.json({token,user:{name:user.name,email:user.email,role:user.role}});}catch(e){next(e)}});
router.get('/me',requireAuth,(req,res)=>res.json({user:req.user}));
export default router;
